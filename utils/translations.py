def get_current_language() -> str:
    """Returns current active language: 'English' or 'हिंदी'."""
    return st.session_state.get("app_language", "English")


def t(key: str, default_text: str = None) -> str:
    """Translates key to current active language, with fallback to English or default."""
    current_lang = "hi" if get_current_language() == "हिंदी" else "en"
    lang_dict = TRANSLATIONS.get(current_lang, {})
    if key in lang_dict:
        return lang_dict[key]
    # Fallback to English dict
    return TRANSLATIONS.get("en", {}).get(key, default_text or key)
